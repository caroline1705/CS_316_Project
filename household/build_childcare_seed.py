"""Generate seed_childcare.sql from the DOL National Database of Childcare Prices.

Download NDCP2022.xlsx from https://www.dol.gov/sites/dolgov/files/WB/NDCP2022.xlsx
(not committed: ~90 MB), then run:  python3 build_childcare_seed.py NDCP2022.xlsx
"""
import statistics
import sys

import openpyxl

STATE, YEAR = "NC", 2022
# NDCP column -> (provider, age_group). Prices are weekly medians for full-time care.
COLUMNS = {
    "MCINFANT": ("CENTER", "INFANT"),       "MCTODDLER": ("CENTER", "TODDLER"),
    "MCPRESCHOOL": ("CENTER", "PRESCHOOL"), "MCSA": ("CENTER", "SCHOOL_AGE"),
    "MFCCINFANT": ("HOME", "INFANT"),       "MFCCTODDLER": ("HOME", "TODDLER"),
    "MFCCPRESCHOOL": ("HOME", "PRESCHOOL"), "MFCCSA": ("HOME", "SCHOOL_AGE"),
}


def main(path):
    ws = openpyxl.load_workbook(path, read_only=True).worksheets[0]
    rows = ws.iter_rows(values_only=True)
    ix = {name: i for i, name in enumerate(next(rows))}

    values, counties, skipped = [], [], 0
    by_key = {}                                    # (provider, age) -> list of prices
    for r in rows:
        if r[ix["STATE_ABBREVIATION"]] != STATE or r[ix["STUDYYEAR"]] != YEAR:
            continue
        county = r[ix["COUNTY_NAME"]].removesuffix(" County").replace("'", "''")
        fips = str(r[ix["COUNTY_FIPS_CODE"]]).zfill(5)
        counties.append(f"('{STATE}','{county}','{fips}')")
        for col, (provider, age) in COLUMNS.items():
            price = r[ix[col]]
            if not isinstance(price, (int, float)):   # missing value in source
                skipped += 1
                continue
            values.append(f"('{STATE}','{county}','{fips}',{YEAR},'{provider}','{age}',{price:.2f})")
            by_key.setdefault((provider, age), []).append(price)

    # State-wide median, used when a county has no data (same idea as GSA 'STANDARD')
    for (provider, age), prices in sorted(by_key.items()):
        med = statistics.median(prices)
        values.append(f"('{STATE}','STANDARD',NULL,{YEAR},'{provider}','{age}',{med:.2f})")

    with open("seed_childcare.sql", "w") as f:
        f.write("-- Source: U.S. Department of Labor, National Database of Childcare Prices (NDCP 2008-2022)\n")
        f.write("-- https://www.dol.gov/agencies/wb/topics/featured-childcare\n")
        f.write(f"-- {STATE} counties, study year {YEAR}; weekly median price for full-time care.\n")
        f.write("-- 'STANDARD' rows = median across NC counties (fallback for missing counties).\n")
        f.write("-- Generated by build_childcare_seed.py -- do not edit by hand.\n")
        f.write("INSERT INTO county (state, county, county_fips) VALUES\n ")
        f.write(",\n ".join(counties) + ";\n\n")
        f.write("INSERT INTO childcare_price\n (state, county, county_fips, study_year, provider, age_group, weekly_price) VALUES\n ")
        f.write(",\n ".join(values) + ";\n")
    print(f"wrote {len(counties)} counties and {len(values)} price rows ({skipped} missing values skipped) to seed_childcare.sql")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "NDCP2022.xlsx")
